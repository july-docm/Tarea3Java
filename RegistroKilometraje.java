    private void btnAgregarRutaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarRutaActionPerformed
        try {
    if (indice < 7) {
        double distancia = Double.parseDouble(
            txtKilometraje.getText().trim()
        );

        if (distancia < 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Ingresa una distancia válida."
            );
            return;
        }

        kilometros[indice] = distancia;
        indice++;

        txtKilometraje.setText("");

        javax.swing.JOptionPane.showMessageDialog(
            this, "Ruta agregada correctamente."
        );

    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Ya ingresaste las 7 rutas."
        );
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Ingresa un número válido."
    );
}// TODO add your handling code here:
    }//GEN-LAST:event_btnAgregarRutaActionPerformed

    private void btnGenerarReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarReporteActionPerformed
    if (indice != 7) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Debes ingresar las 7 rutas primero."
    );
    return;
}

double total = 0;

for (int i = 0; i < 7; i++) {
    total += kilometros[i];
}

double promedio = total / 7;

String reporte = "Reporte Semanal de Rutas\n"
        + "Total de Kilómetros: " + total + "\n"
        + "Promedio Diario: " + promedio;

try {
    java.io.File carpeta = new java.io.File("temp");
    carpeta.mkdirs();

    java.io.FileWriter escritor =
        new java.io.FileWriter(
            "temp/julia_reporte_rutas.txt"
        );

    escritor.write(reporte);
    escritor.close();

    javax.swing.JOptionPane.showMessageDialog(
        this, "Reporte guardado en la carpeta temp."
    );

} catch (java.io.IOException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Error al guardar el reporte."
    );
}    // TODO add your handling code here:
    }//GEN-LAST:event_btnGenerarReporteActionPerformed

