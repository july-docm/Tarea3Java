private void cargarDiscos() {
    try {
        java.io.File archivo =
            new java.io.File("temp/discos.csv");

        java.util.Scanner lector =
            new java.util.Scanner(archivo);

        cantidad = 0;

        while (lector.hasNextLine() && cantidad < 5) {
            String linea = lector.nextLine();
            String[] datos = linea.split(",");

            if (datos.length == 2) {
                titulos[cantidad] = datos[0].trim();
                anios[cantidad] =
                    Integer.parseInt(datos[1].trim());
                cantidad++;
            }
        }

        lector.close();

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error al cargar los discos: " + e.getMessage()
        );
    }
}
