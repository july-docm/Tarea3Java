    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
String album = txtBuscarAlbum.getText().trim();

if (album.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Escribe el nombre del álbum."
    );
    return;
}

int posicion = -1;

for (int i = 0; i < cantidad; i++) {
    if (titulos[i].equalsIgnoreCase(album)) {
        posicion = i;
        break;
    }
}

if (posicion == -1) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Álbum no encontrado."
    );
    return;
}

try {
    int nuevoAnio = Integer.parseInt(
        txtNuevoAnio.getText().trim()
    );

    anios[posicion] = nuevoAnio;

    java.io.FileWriter escritor =
        new java.io.FileWriter("temp/discos.csv", false);

    for (int i = 0; i < cantidad; i++) {
        escritor.write(
            titulos[i] + "," + anios[i]
            + System.lineSeparator()
        );
    }

    escritor.close();

    lblAnioActual.setText(
        String.valueOf(nuevoAnio)
    );
    txtNuevoAnio.setText("");

    javax.swing.JOptionPane.showMessageDialog(
        this, "Registro actualizado correctamente."
    );

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Ingresa un año válido."
    );
} catch (java.io.IOException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Error al guardar los cambios."
    );
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnActualizarActionPerformed

