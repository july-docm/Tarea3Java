    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
String titulo = txtTitulo.getText().trim();
String consola = txtConsola.getText().trim();
String textoAnio = txtAnio.getText().trim();

if (titulo.isEmpty() || consola.isEmpty() || textoAnio.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Completa todos los campos.");
    return;
}

try {
    int anio = Integer.parseInt(textoAnio);

    if (anio <= 0) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Ingresa un año válido.");
        return;
    }

    Videojuego juego = new Videojuego(titulo, consola, anio);
    videojuegos.add(juego);

    javax.swing.JOptionPane.showMessageDialog(
            this, "Videojuego agregado correctamente.");

    txtTitulo.setText("");
    txtConsola.setText("");
    txtAnio.setText("");

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "El año debe ser un número entero.");
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed

StringBuilder catalogo = new StringBuilder();

if (videojuegos.isEmpty()) {
    catalogo.append("El catálogo está vacío.");
} else {
    for (int i = 0; i < videojuegos.size(); i++) {
        catalogo.append("Videojuego ").append(i + 1).append("\n");
        catalogo.append(videojuegos.get(i).mostrarDatos());
        catalogo.append("\n\n--------------------\n\n");
    }
}

txtCatalogo.setText(catalogo.toString());
        // TODO add your handling code here:
    }//GEN-LAST:event_btnMostrarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed

if (videojuegos.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "No hay videojuegos para eliminar.");
    return;
}

Videojuego eliminado = videojuegos.remove(videojuegos.size() - 1);

javax.swing.JOptionPane.showMessageDialog(
        this, "Se eliminó: " + eliminado.titulo);

StringBuilder catalogo = new StringBuilder();

for (int i = 0; i < videojuegos.size(); i++) {
    catalogo.append("Videojuego ").append(i + 1).append("\n");
    catalogo.append(videojuegos.get(i).mostrarDatos());
    catalogo.append("\n\n--------------------\n\n");
}

if (videojuegos.isEmpty()) {
    catalogo.append("El catálogo está vacío.");
}

txtCatalogo.setText(catalogo.toString());
        // TODO add your handling code here:
    }//GEN-LAST:event_btnEliminarActionPerformed

