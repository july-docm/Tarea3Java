    private void btnCrearCancionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearCancionActionPerformed

String titulo = txtTituloCancion.getText().trim();
String textoDuracion = txtDuracion.getText().trim();
String genero = txtGenero.getText().trim();
String artistaNombre = txtArtistaCancion.getText().trim();

if (titulo.isEmpty() || textoDuracion.isEmpty()
        || genero.isEmpty() || artistaNombre.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Completa todos los campos de la canción."
    );
    return;
}

try {
    int duracion = Integer.parseInt(textoDuracion);

    if (duracion <= 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "La duración debe ser mayor que cero."
        );
        return;
    }

    Cancion cancion = new Cancion(
        titulo, duracion, genero, artistaNombre
    );

    registro.append("=== CANCIÓN ===\n");
    registro.append(cancion.mostrarDatos()).append("\n\n");

    txtResultados.setText(registro.toString());

    txtTituloCancion.setText("");
    txtDuracion.setText("");
    txtGenero.setText("");
    txtArtistaCancion.setText("");

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "La duración debe ser un número entero."
    );
}
        // TODO add your handling code here:
    }//GEN-LAST:event_btnCrearCancionActionPerformed

