    private void btnCargarDatosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarDatosActionPerformed
    try {
    java.io.File archivo =
        new java.io.File("temp/temperaturas.txt");

    java.util.Scanner lector =
        new java.util.Scanner(archivo);

    indice = 0;

    while (lector.hasNextLine() && indice < 6) {
        String linea = lector.nextLine().trim();

        if (!linea.isEmpty()) {
            temperaturas[indice] =
                Double.parseDouble(linea);
            indice++;
        }
    }

    lector.close();

    if (indice == 6) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Los datos se cargaron correctamente."
        );
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, "El archivo debe contener 6 temperaturas."
        );
    }

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Error al leer el archivo: " + e.getMessage()
    );
}    // TODO add your handling code here:
    }//GEN-LAST:event_btnCargarDatosActionPerformed

    private void btnCalcularEstadisticasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularEstadisticasActionPerformed
    if (indice != 6) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Primero debes cargar las 6 temperaturas."
    );
    return;
}

double suma = 0;
int calidos = 0;
int frescos = 0;

for (int i = 0; i < 6; i++) {
    suma += temperaturas[i];

    if (temperaturas[i] >= 25.0) {
        calidos++;
    } else {
        frescos++;
    }
}

double promedio = suma / 6;

String resultado = "Análisis Climático\n\n"
        + "------------------\n\n"
        + "Promedio de Temperatura: "
        + String.format("%.2f", promedio) + "\n\n"
        + "Días Cálidos (>= 25°): "
        + calidos + "\n\n"
        + "Días Frescos (< 25°): "
        + frescos;

txtResultados.setText(resultado);    // TODO add your handling code here:
    }//GEN-LAST:event_btnCalcularEstadisticasActionPerformed

