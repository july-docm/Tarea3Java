    private void btnAgregarTareaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarTareaActionPerformed
    if (indice < 5) {
    String tarea = txtTarea.getText().trim();

    if (tarea.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Escribe una tarea primero."
        );
        return;
    }

    tareas[indice] = tarea;
    indice++;

    txtListaTareas.append(
        indice + ". " + tarea + "\n"
    );

    txtTarea.setText("");

} else {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Ya ingresaste las 5 tareas."
    );
}    // TODO add your handling code here:
    }//GEN-LAST:event_btnAgregarTareaActionPerformed

    private void btnExportarAgendaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarAgendaActionPerformed
    if (indice != 5) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Debes ingresar las 5 tareas primero."
    );
    return;
}

try {
    java.io.File carpeta = new java.io.File("temp");
    carpeta.mkdirs();

    java.io.FileWriter escritor =
        new java.io.FileWriter("temp/julia_agenda.txt");

    escritor.write("Agenda de Tareas\n");

    for (int i = 0; i < 5; i++) {
        escritor.write((i + 1) + ". " + tareas[i] + "\n");
    }

    escritor.close();

    javax.swing.JOptionPane.showMessageDialog(
        this, "Agenda exportada correctamente."
    );

} catch (java.io.IOException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Error al guardar la agenda."
    );
}    // TODO add your handling code here:
    }//GEN-LAST:event_btnExportarAgendaActionPerformed

